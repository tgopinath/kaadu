#!/usr/bin/env python3
"""Resolve every scientific / group name in data.js to an iNaturalist taxon ID and write ids.js.
Uses curl (node's fetch is unreliable on this network); keeps IDs already in ids.js."""
import json, re, subprocess, time, pathlib, urllib.parse
root = pathlib.Path(__file__).resolve().parent.parent
src = (root / 'data.js').read_text()
names = set(re.findall(r"sci: '([^']+)'", src))
for block in re.findall(r"taxa: \[([^\]]+)\]", src):
    names |= set(re.findall(r"'([^']+)'", block))
ids_file = root / 'ids.js'
known = {}
if ids_file.exists():
    m = re.search(r'=\s*(\{.*\});', ids_file.read_text(), re.S)
    if m: known = json.loads(m.group(1))
# Names iNaturalist files under a different accepted name (checked by hand with /taxa/autocomplete).
known.update({'Hibiscus rosa-sinensis': 1628098, 'Murraya koenigii': 1579705, 'Dracaena trifasciata': 67710, 'Alsophila gigantea': 1414806})
def get(url):
    for _ in range(4):
        r = subprocess.run(['curl', '-s', '-m', '15', url], capture_output=True, text=True)
        try: return json.loads(r.stdout)
        except Exception: time.sleep(2)
    return None
for n in sorted(names - set(known)):
    d = get('https://api.inaturalist.org/v1/taxa?' + urllib.parse.urlencode({'q': n, 'taxon_id': 47126, 'per_page': 10, 'is_active': 'true'}))
    hit = next((t for t in (d or {}).get('results', []) if t['name'].lower() == n.lower()), None)
    if hit: known[n] = hit['id']
    print(n, hit['id'] if hit else 'MISSING', flush=True)
    time.sleep(0.4)
ids_file.write_text('// iNaturalist taxon IDs for the names in data.js. Generated by tools/resolve-ids.py.\nexport const IDS = ' + json.dumps(dict(sorted(known.items())), indent=0) + ';\n')
print('wrote', len(known), 'of', len(names))
